package io.coreback.relayremote.protocol.companion

import java.util.Base64
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Test

class RtiKeyboardArchiveTest {
    private val session = "0123456789abcdef".encodeToByteArray()

    @Test
    fun `reads keyboard session generated by pyatv reference fixture`() {
        val payload = Base64.getDecoder().decode(
            "YnBsaXN0MDDSAQIDCFQkdG9wWCRvYmplY3Rz0gQFBgdbc2Vzc2lvblVVSURdZG9jdW1lbnRTdGF0ZYABgAKlCQoLDhFVJG51bGxPEBAwMTIzNDU2Nzg5YWJjZGVm0QwNVWRvY1N0gAPRDxBfEBJjb250ZXh0QmVmb3JlSW5wdXSABFhFeGlzdGluZwgNEhsgLDo8PkRKXWBmaGuAggAAAAAAAAEBAAAAAAAAABIAAAAAAAAAAAAAAAAAAACL",
        )

        val parsed = RtiKeyboardArchive.readSession(payload)

        assertArrayEquals(session, parsed?.uuid)
        assertEquals("Existing", parsed?.currentText)
    }

    @Test
    fun `clear and insert archives resolve through keyed object references`() {
        val clear = RtiKeyboardArchive.clearText(session)
        val insert = RtiKeyboardArchive.inputText(session, "Relay")

        assertArrayEquals(
            session,
            RtiKeyboardArchive.readPath(
                clear,
                "textOperations",
                "targetSessionUUID",
                "NS.uuidbytes",
            ) as ByteArray,
        )
        assertEquals(
            "",
            RtiKeyboardArchive.readPath(clear, "textOperations", "textToAssert"),
        )
        assertEquals(
            "Relay",
            RtiKeyboardArchive.readPath(
                insert,
                "textOperations",
                "keyboardOutput",
                "insertionText",
            ),
        )
    }
}
